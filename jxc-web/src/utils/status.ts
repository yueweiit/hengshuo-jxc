export type StatusDomain = keyof typeof DOMAIN_STATUS

export function statusDef(status: string | null | undefined, domain?: string): StatusDef {
  if (!status) return { label: '-', type: 'info' }
  return (domain && DOMAIN_STATUS[domain]?.[status]) || STATUS[status] || { label: status, type: 'info' }
}
